import { addAuditEvent, getAuthenticatedActor, hasPermission } from '../../../lib/procurement-db';
import { assertSupabase, getSupabaseServer } from '../../../lib/supabase-server';

export const dynamic = 'force-dynamic';

function csvCell(value: unknown) {
  let text = '';
  if (typeof value === 'string') text = value;
  else if (typeof value === 'number' || typeof value === 'boolean' || typeof value === 'bigint') text = value.toString();
  else if (value !== null && value !== undefined) text = JSON.stringify(value);
  return /[",\n]/.test(text) ? `"${text.replaceAll('"', '""')}"` : text;
}

export async function GET(request: Request) {
  try {
    const actor = await getAuthenticatedActor(request);
    if (!actor) return Response.json({ error: 'Sign-in required.' }, { status: 401 });
    if (!hasPermission(actor.role, 'reports:export')) return Response.json({ error: 'Your role cannot export evidence reports.' }, { status: 403 });

    const supabase = getSupabaseServer();
    const [transactionsResult, latestScanResult] = await Promise.all([
      supabase.from('procurement_transactions').select('id, supplier, amount, pattern, risk_score, status, reason, source_file, created_at').order('risk_score', { ascending: false }).order('created_at', { ascending: false }),
      supabase.from('scan_runs').select('records_scanned, flagged_count, mean_risk, max_risk, duration_ms, created_at').order('created_at', { ascending: false }).limit(1).maybeSingle(),
    ]);
    assertSupabase(transactionsResult); assertSupabase(latestScanResult);
    const transactions = transactionsResult.data ?? [];
    const latestScan = latestScanResult.data;
    const lines = [
      ['ProcureGuard AI evidence report'],
      ['Generated at', new Date().toISOString()],
      ['Generated by', actor.email],
      ['Records included', transactions.length],
      ['Latest scan records', latestScan?.records_scanned ?? 'Not available'],
      ['Latest scan flagged', latestScan?.flagged_count ?? 'Not available'],
      ['Latest scan mean risk', latestScan?.mean_risk ?? 'Not available'],
      ['Latest scan peak risk', latestScan?.max_risk ?? 'Not available'],
      ['Latest scan duration ms', latestScan?.duration_ms ?? 'Not available'],
      [],
      ['Transaction ID', 'Supplier', 'Amount USD', 'Pattern', 'Risk Score', 'Status', 'Reason', 'Source File', 'Created At'],
      ...transactions.map((row) => [row.id, row.supplier, row.amount, row.pattern, row.risk_score, row.status, row.reason, row.source_file, row.created_at]),
    ];
    const csv = lines.map((line) => line.map(csvCell).join(',')).join('\n') + '\n';
    await addAuditEvent(actor.userId, 'report_export', `Evidence report exported with ${transactions.length} procurement records.`);
    return new Response(csv, {
      headers: {
        'Content-Type': 'text/csv; charset=utf-8',
        'Content-Disposition': `attachment; filename="procureguard-evidence-${new Date().toISOString().slice(0, 10)}.csv"`,
        'Cache-Control': 'no-store',
      },
    });
  } catch (error) {
    return Response.json({ error: error instanceof Error ? error.message : 'Evidence report unavailable.' }, { status: 503 });
  }
}
